const {chromium}=require(process.env.MOTION_PLAYWRIGHT_MODULE);
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const output=process.argv[2];
const url=process.env.BIRTHDAY_URL||'http://127.0.0.1:4173/';
(async()=>{
 await fs.mkdir(output,{recursive:true});
 const browser=await chromium.launch({headless:true});
 const report={url,checks:[],errors:[]};
 const film='.player-frame video.film-video';
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  page.on('pageerror',e=>report.errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)report.errors.push(`${r.status()} ${r.url()}`);});
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'静音打开',exact:true}).click();
  await page.locator('.player-frame').scrollIntoViewIfNeeded();
  await page.locator(film).waitFor({timeout:30000});
  assert.match(await page.locator('.section-heading').first().innerText(),/74 秒/);
  assert.equal(await page.locator('.photo-grid .photo-card').count(),19);
  assert.equal(await page.locator('[data-testid="background-audio"]').evaluate(a=>a.paused),true);
  assert.equal(await page.locator(film).evaluate(v=>v.muted),true);
  const meta=await page.locator(film).evaluate(v=>({src:v.getAttribute('src'),duration:v.duration||0,ready:v.readyState}));
  assert.match(meta.src,/film-510\.mp4/);
  await page.waitForFunction(sel=>{const v=document.querySelector(sel);return v&&Number.isFinite(v.duration)&&v.duration>0;},film,{timeout:30000});
  const duration=await page.locator(film).evaluate(v=>v.duration);
  assert.ok(Math.abs(duration-74)<0.2,`film duration ${duration}`);
  await page.locator('#film').screenshot({path:path.join(output,'website-desktop.png')});
  report.checks.push(`74-second label; 19 photos; silent entry; film master ${duration.toFixed(2)}s muted on entry`);
  await page.getByRole('button',{name:'声音关'}).click();
  await page.waitForFunction(()=>!document.querySelector('[data-testid="background-audio"]').paused);
  assert.equal(await page.locator(film).evaluate(v=>v.muted),false);
  await page.locator(film).evaluate(v=>v.play());
  await page.waitForFunction(sel=>{const v=document.querySelector(sel);return v&&v.currentTime>0.5;},film,{timeout:30000});
  await page.getByRole('button',{name:'看完整现场视频'}).click();
  await page.locator('dialog video').waitFor();
  assert.equal(await page.locator('[data-testid="background-audio"]').evaluate(a=>a.paused),true);
  assert.equal(await page.locator(film).evaluate(v=>v.paused),true,'modal must pause the film');
  assert.equal(await page.locator('dialog video').evaluate(v=>v.muted),true);
  await page.getByRole('button',{name:'关闭大图或视频'}).click();
  report.checks.push('Sound toggle; film plays and unmutes; modal pauses film/background; original video defaults muted');
  await page.locator('.photo-grid .photo-card').first().click();
  await page.getByRole('button',{name:'下一张'}).click();
  assert.match(await page.locator('.dialog-top').innerText(),/2 \/ 19/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').count(),0);
  report.checks.push('Gallery next photo and Escape close');
  await page.getByRole('button',{name:'今天就放过我'}).click();
  assert.equal(await page.locator('.birthday-final').innerText(),'生日快乐！');
  report.checks.push('Birthday ending exact text');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#film').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#film').screenshot({path:path.join(output,'website-mobile.png')});
  report.checks.push('390px mobile layout without horizontal overflow');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'静音打开',exact:true}).click();
  await page.locator(film).waitFor();
  await page.locator('.player-frame').scrollIntoViewIfNeeded();
  const stage=page.locator('.player-frame');
  const shotA=await stage.screenshot();
  await page.locator(film).evaluate(v=>{v.currentTime=2;v.play();});
  await page.waitForTimeout(2300);
  const shotB=await stage.screenshot();
  assert.equal(Buffer.compare(shotA,shotB)===0,false,'film stage did not change: playback is not advancing');
  await page.locator(film).evaluate(v=>v.pause());
  report.checks.push('Film advances in the site player (frames change during playback)');
  await page.getByRole('link',{name:'再公开一次'}).click();
  await page.waitForTimeout(400);
  assert.ok((await page.locator(film).evaluate(v=>v.currentTime))<1,'footer replay must seek back to the start');
  report.checks.push('Footer "再公开一次" pauses and seeks the film back to 0');
  report.status=report.errors.length?'failed':'passed';
  assert.equal(report.errors.length,0,JSON.stringify(report.errors));
 }catch(e){report.status='failed';report.failure=e.stack;throw e;}
 finally{await fs.writeFile(path.join(output,'website-checks.json'),JSON.stringify(report,null,2));await browser.close();console.log(JSON.stringify(report,null,2));}
})().catch(e=>{console.error(e);process.exitCode=1;});
